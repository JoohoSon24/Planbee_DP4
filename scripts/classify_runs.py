"""Classify legacy run transcripts without changing their original bodies.

Explicit metadata wins; otherwise preserve evidence and confidence in classification.json.
Usage: .venv/bin/python scripts/classify_runs.py [--apply] [--known-live FILE ...]
"""
from pathlib import Path
from collections import Counter
import argparse
import hashlib
import json
import re
import sqlite3
from datetime import datetime
from zoneinfo import ZoneInfo

ROOT=Path(__file__).resolve().parents[1]


def classify(text, name, corpus, known_live):
    explicit=re.search(r'^- LLM 모드: (mock|live|mixed|unknown)\b',text,re.M)
    if explicit:return explicit[1],'explicit','existing mode header'
    if name in known_live:return 'live','session_inferred','user-referenced Live run in this session; no historical runtime metadata'
    reasons=re.findall(r'^사유: (.+)$',text,re.M)
    reasons=[r for r in reasons if not re.fullmatch(r'.+ \d+건',r)]
    matched=[r for r in reasons if r in corpus]
    unmatched=[r for r in reasons if r not in corpus]
    # Require a real scripted-model output, not generic code status text or timestamps.
    if matched and not unmatched:
        return 'mock','script_inferred','all recorded model rationale strings match local Mock seeds/test source: '+json.dumps(matched,ensure_ascii=False)
    if name=='2026-11-19_11-24-02_422728_41eadb71.md':
        return 'mock','confirmed_test','generated by test_final_hive_constraints_after_consents_rollback_initial_offer in this session'
    return 'unknown','unresolved','no recorded runtime mode; insufficient evidence to distinguish Live, Mock or test adapter'


def migrate(root, apply=False, known_live=()):
    corpus='\n'.join(p.read_text() for pattern in ['seed/**/mock_llm.yaml','tests/*.py','app/llm.py'] for p in ROOT.glob(pattern))
    files=sorted(root.glob('*.md'))
    records=[]
    for p in files:
        content=p.read_bytes();text=content.decode('utf-8')
        mode,confidence,evidence=classify(text,p.name,corpus,set(known_live))
        target=root/mode/p.name
        if target.exists():raise ValueError(f'Destination exists: {target}')
        records.append(dict(file=p.name,mode=mode,confidence=confidence,evidence=evidence,
            source=p.name,target=f'{mode}/{p.name}',sha256=hashlib.sha256(content).hexdigest()))
    print(json.dumps(dict(counts=dict(Counter(r['mode'] for r in records)),
                         unknown=[r['file'] for r in records if r['mode']=='unknown']),ensure_ascii=False,indent=2))
    if not apply:return records
    prior=root/'classification.json'
    data=json.loads(prior.read_text()) if prior.exists() else dict(records=[])
    data['records']+=records
    data['updated_at']=datetime.now(ZoneInfo('Asia/Seoul')).isoformat()
    # Write the classification audit before moves so interrupted runs remain traceable.
    root.mkdir(exist_ok=True)
    prior.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
    for r in records:
        source=root/r['source'];target=root/r['target'];target.parent.mkdir(exist_ok=True)
        source.rename(target)
        assert hashlib.sha256(target.read_bytes()).hexdigest()==r['sha256']
    mapping={r['file']:r for r in data['records']}
    # Update only transcript references, not assignments, settings or run decisions.
    for path in ROOT.glob('*.db'):
        db=sqlite3.connect(path,timeout=5)
        try:
            tables={r[0] for r in db.execute("select name from sqlite_master where type='table'")}
            if 'run' not in tables:continue
            for rid,raw in db.execute('select id,ctx from run').fetchall():
                ctx=json.loads(raw);name=ctx.get('transcript_file')
                if name not in mapping:continue
                r=mapping[name]
                ctx.update(transcript_file=r['target'],llm_mode=r['mode'],llm_modes=[r['mode']],
                    transcript_mode_evidence=r['evidence'],transcript_mode_confidence=r['confidence'])
                db.execute('update run set ctx=? where id=?',(json.dumps(ctx,ensure_ascii=False),rid))
            db.commit()
        finally:db.close()
    return records


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apply',action='store_true')
    parser.add_argument('--known-live',nargs='*',default=[])
    args=parser.parse_args()
    migrate(ROOT/'runs',args.apply,args.known_live)
